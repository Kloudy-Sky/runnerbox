import type { HostInstall } from "../launcher/launcher-config.ts";
import { psQuote, windowsPaths } from "./windows-paths.ts";

// The script the job task runs as the job user, in a profile Windows has just created: it unpacks
// a fresh runner and runs one job. Its environment is that new profile's, so nothing of the
// owner's reaches the job. Git's bash goes on PATH because workflows use `shell: bash`.
export function windowsRunnerScript(config: HostInstall) {
  const [runner] = config.runners;
  if (!runner) throw new Error("A host install needs one runner.");
  const paths = windowsPaths(config);
  const env = {
    ...runner.env,
    ...(runner.allowedWorkflows ? { ACTIONS_RUNNER_HOOK_JOB_STARTED: paths.jobStarted } : {}),
  };

  return `# Runs one job as the job user. Generated by runnerbox host render.
$ErrorActionPreference = 'Stop'
$handoff = ${psQuote(paths.handoff)}
$code = 1
try {
  $registration = (Get-Content -Raw -LiteralPath "$handoff\\registration").Trim()
  $work = Join-Path $env:USERPROFILE 'runner'
  New-Item -ItemType Directory -Path $work | Out-Null
  tar -xf ${psQuote(paths.runnerArchive)} -C $work
  if ($LASTEXITCODE -ne 0) { throw 'could not unpack the runner' }
  $env:PATH = "C:\\Program Files\\Git\\bin;$env:PATH"
${Object.entries(env).map(([key, value]) => `  [Environment]::SetEnvironmentVariable(${psQuote(key)}, ${psQuote(value)})\n`).join("")}  Set-Location $work
  # The registration becomes an argument of the runner, which the job could read anyway, and it
  # works for this one job only. cmd does the redirect: PowerShell 5.1 would turn the runner's
  # first line on stderr into an error that stops this script.
  cmd /c "\`"$work\\run.cmd\`" --jitconfig $registration > \`"$handoff\\runner.log\`" 2>&1"
  $code = $LASTEXITCODE
} catch {
  Add-Content -LiteralPath "$handoff\\runner.log" -Value "job.ps1: $_"
} finally {
  Set-Content -LiteralPath "$handoff\\exit" -Value $code
}
`;
}
