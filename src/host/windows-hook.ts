import type { HostRunnerType } from "../launcher/launcher-config.ts";
import { psQuote } from "./windows-paths.ts";

// The Windows form of the job-started hook: fails every job whose workflow isn't on the kind's
// list. The config's pattern characters mean the same to -clike as to the shell: only `*` is special.
export function windowsJobStartedHook(allowedWorkflows: NonNullable<HostRunnerType["allowedWorkflows"]>) {
  return `# Generated by runnerbox host render.
$ref = $env:GITHUB_WORKFLOW_REF
foreach ($pattern in @(${allowedWorkflows.map(psQuote).join(", ")})) {
  if ($ref -clike $pattern) { exit 0 }
}
Write-Output "::error::This runner doesn't accept jobs from $ref."
exit 1
`;
}
