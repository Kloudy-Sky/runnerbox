import { shellQuote } from "../launcher/docker-command.ts";
import type { HostInstall } from "../launcher/launcher-config.ts";
import { installPaths } from "./install-paths.ts";

// The script that runs one job on macOS. `up` runs it as root through one sudoers rule and sends the
// single-use registration on stdin. It takes no arguments and reads nothing the job user can write,
// so that rule grants nothing beyond what's written here. It wipes the job user before and after
// the job: a job that leaves a process or a file behind could otherwise read the next job's secrets.
export function jobScript(config: HostInstall) {
  const [runner] = config.runners;
  if (!runner) throw new Error("A host install needs one runner.");
  const paths = installPaths(config);
  const q = shellQuote;
  const env = {
    ...runner.env,
    ...(runner.allowedWorkflows ? { ACTIONS_RUNNER_HOOK_JOB_STARTED: paths.jobStarted } : {}),
  };

  return `#!/bin/bash
# Runs one job as ${config.host.user}, then removes everything it left. Generated by \`runnerbox host render\`.
set -euo pipefail
JOB_USER=${q(config.host.user)}
JOB_HOME="/Users/$JOB_USER"
RUNNER_ARCHIVE=${q(paths.runnerArchive)}
PF_ANCHOR=${q(paths.pfAnchor)}
PF_RULES=${q(paths.pfRules)}

fail() { echo "run-job: $*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || fail "must run as root, through sudo."
# The caller's folder is usually inside the owner's home, which the job user can't enter.
cd /
JOB_UID="$(id -u "$JOB_USER")" || fail "user $JOB_USER doesn't exist. Run setup.sh."
# Only the account setup.sh made: cleanup kills its processes and deletes its files, so pointing
# this at anyone's real account would wipe it.
dscl . -read "/Users/$JOB_USER" RealName 2>/dev/null | grep -q 'runnerbox jobs' || fail "$JOB_USER wasn't created by setup.sh."
[ "$JOB_USER" != "\${SUDO_USER:-}" ] || fail "$JOB_USER is the account that runs up."
dseditgroup -o checkmember -m "$JOB_USER" admin >/dev/null && fail "$JOB_USER is an administrator."
[ -f "$RUNNER_ARCHIVE" ] || fail "$RUNNER_ARCHIVE is missing. Run setup.sh."

clean() {
  # Services the job registered would be restarted by launchd as fast as they're killed.
  launchctl bootout "user/$JOB_UID" 2>/dev/null || true
  for _ in 1 2 3 4 5; do
    pgrep -U "$JOB_UID" >/dev/null || break
    pkill -KILL -U "$JOB_UID" || true
    sleep 1
  done
  if pgrep -U "$JOB_UID" >/dev/null; then echo "run-job: $JOB_USER still has processes running." >&2; return 1; fi
  crontab -u "$JOB_USER" -r 2>/dev/null || true
  # The places a standard user can write outside its home. Its own temp folders sit two levels
  # down in /private/var/folders.
  find /private/var/folders -mindepth 2 -maxdepth 2 -user "$JOB_USER" -exec rm -rf {} + 2>/dev/null || true
  find /private/tmp /private/var/tmp /Users/Shared -xdev -user "$JOB_USER" -delete 2>/dev/null || true
  # macOS won't let even root remove an account's home folder, or the app containers and a few
  # other folders it keeps under Library. So the home is emptied as far as it goes, and the job only
  # starts if what's left is under Library and isn't a keychain or a launch agent: nothing the next
  # job would run or sign with. A file the job locked would survive too.
  install -d -o "$JOB_USER" -g "$(id -g "$JOB_USER")" -m 700 "$JOB_HOME"
  chflags -R nouchg "$JOB_HOME" 2>/dev/null || true
  find "$JOB_HOME" -mindepth 1 -delete 2>/dev/null || true
  left="$(find "$JOB_HOME" -mindepth 1 \\( -path "$JOB_HOME/Library/Keychains/*" -o -path "$JOB_HOME/Library/LaunchAgents/*" \\
    -o \\( ! -path "$JOB_HOME/Library" ! -path "$JOB_HOME/Library/*" \\) \\) -print -quit 2>/dev/null || true)"
  if [ -n "$left" ]; then echo "run-job: couldn't remove $left." >&2; return 1; fi
}

# The ports other accounts are listening on, as a pf list. pf sees who sent a loopback packet or
# who receives it, never both, so it can't simply keep the job away from other accounts' listeners.
# A job still has to reach its own, so the job user is blocked from every port someone else holds.
other_ports() {
  lsof -nP "$@" -F un 2>/dev/null | awk -v job="$JOB_UID" '
    /^u/ { uid = substr($0, 2) }
    /^n/ && uid != job { n = split($0, part, ":"); if (part[n] ~ /^[0-9]+$/) print part[n] }' | sort -un | paste -sd, -
}

load_filter() {
  local tcp udp
  tcp="$(other_ports -iTCP -sTCP:LISTEN)"
  udp="$(other_ports -iUDP)"
  {
    cat "$PF_RULES"
    [ -z "$tcp" ] || echo "block return out quick on lo0 proto tcp to port { $tcp } user $JOB_UID"
    [ -z "$udp" ] || echo "block return out quick on lo0 proto udp to port { $udp } user $JOB_UID"
  } | pfctl -q -a "$PF_ANCHOR" -f - 2>/dev/null
}

IFS= read -r JIT
[ -n "$JIT" ] || fail "no registration on stdin."

# Fail closed: without the filter a job could reach this machine's own services, the LAN and a tailnet.
load_filter || fail "couldn't load the packet filter rules."
pfctl -s info 2>/dev/null | grep -q '^Status: Enabled' || pfctl -q -E 2>/dev/null
pfctl -s info 2>/dev/null | grep -q '^Status: Enabled' || fail "couldn't enable the packet filter."
# Ports another account opens during the job are closed to it within a few seconds.
while sleep 5; do load_filter || true; done &
FILTER_LOOP=$!

# Whatever an earlier job left, if this script was killed before it could clean up.
trap 'kill "$FILTER_LOOP" 2>/dev/null; wait "$FILTER_LOOP" 2>/dev/null || true; clean' EXIT
clean

as_job_user() { sudo -u "$JOB_USER" -H "$@"; }
as_job_user mkdir "$JOB_HOME/runner"
as_job_user tar -xzf "$RUNNER_ARCHIVE" -C "$JOB_HOME/runner"
cd "$JOB_HOME/runner"
# A clean environment, so nothing of the owner's reaches the job. caffeinate holds off idle sleep
# for as long as the runner lives. The registration becomes an argument of the runner, which the
# job could read anyway, and it works for this one job only.
status=0
as_job_user env -i \\
  HOME="$JOB_HOME" USER="$JOB_USER" LOGNAME="$JOB_USER" SHELL=/bin/bash LANG=en_US.UTF-8 \\
  PATH=/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin \\
${Object.entries(env).map(([key, value]) => `  ${q(`${key}=${value}`)} \\\n`).join("")}  caffeinate -i ./run.sh --jitconfig "$JIT" </dev/null || status=$?
exit "$status"
`;
}
