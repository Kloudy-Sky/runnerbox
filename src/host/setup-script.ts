import { shellQuote } from "../launcher/docker-command.ts";
import type { HostInstall } from "../launcher/launcher-config.ts";
import { installPaths } from "./install-paths.ts";
import { RUNNER_RELEASE } from "./runner-release.ts";

// The script `host render` writes for macOS. Run with sudo by the user who'll run `up`, from the
// folder it was rendered into. It can be run again after a config change or a runnerbox update.
export function setupScript(config: HostInstall) {
  const paths = installPaths(config);
  const q = shellQuote;
  const vars = {
    JOB_USER: config.host.user,
    INSTALL_DIR: paths.dir,
    RUNNER_ARCHIVE: paths.runnerArchive,
    RUNNER_URL: RUNNER_RELEASE.darwin.url,
    RUNNER_SHA256: RUNNER_RELEASE.darwin.sha256,
    SUDOERS: paths.sudoers,
    RUN_JOB: paths.runJob,
  };

  return `#!/bin/bash
# Sets this Mac up to run jobs as a separate user. Generated by \`runnerbox host render\`. Review it,
# and run-job next to it, before running: sudo ./setup.sh
set -euo pipefail
cd "$(dirname "$0")"
${Object.entries(vars).map(([key, value]) => `${key}=${q(value)}`).join("\n")}

fail() { echo "$*" >&2; exit 1; }

[ "$(uname -s)" = Darwin ] && [ "$(uname -m)" = arm64 ] || fail "This setup is for a Mac with Apple silicon."
[ "$(id -u)" -eq 0 ] || fail "Run with sudo."
OWNER="\${SUDO_USER:-}"
[ -n "$OWNER" ] && [ "$OWNER" != root ] || fail "Run with sudo from the account that will run runnerbox up."
OWNER_HOME="$(dscl . -read "/Users/$OWNER" NFSHomeDirectory | awk '{print $2}')"
for file in run-job pf.rules; do [ -f "$file" ] || fail "$file is missing next to setup.sh."; done

# The account jobs run as: standard, hidden from the login window, with a password nobody knows.
if id "$JOB_USER" >/dev/null 2>&1; then
  dseditgroup -o checkmember -m "$JOB_USER" admin >/dev/null && fail "$JOB_USER exists and is an administrator. Pick another name."
else
  sysadminctl -addUser "$JOB_USER" -fullName "runnerbox jobs" -password "$(openssl rand -base64 30)" -home "/Users/$JOB_USER"
  dscl . -create "/Users/$JOB_USER" IsHidden 1
fi

# The rules name the job user, so they only parse once it exists.
pfctl -nf pf.rules 2>/dev/null || fail "pf.rules doesn't parse."

# Every account on a Mac is in the staff group, and a home folder is often readable by it.
chmod go-rwx "$OWNER_HOME"

install -d -o root -g wheel -m 755 "$INSTALL_DIR"
install -o root -g wheel -m 755 run-job "$RUN_JOB"
install -o root -g wheel -m 644 pf.rules "$INSTALL_DIR/pf.rules"
if [ -f job-started.sh ]; then
  install -o root -g wheel -m 755 job-started.sh "$INSTALL_DIR/job-started.sh"
else
  rm -f "$INSTALL_DIR/job-started.sh"
fi

if ! echo "$RUNNER_SHA256  $RUNNER_ARCHIVE" | shasum -a 256 -c --status 2>/dev/null; then
  curl -fsSL --retry 5 --retry-all-errors "$RUNNER_URL" -o "$RUNNER_ARCHIVE.part"
  echo "$RUNNER_SHA256  $RUNNER_ARCHIVE.part" | shasum -a 256 -c --status || fail "The runner download doesn't match its checksum."
  mv "$RUNNER_ARCHIVE.part" "$RUNNER_ARCHIVE"
  chmod 644 "$RUNNER_ARCHIVE"
fi

# The owner may run that one script as root, and nothing else.
echo "$OWNER ALL=(root) NOPASSWD: $RUN_JOB" > "$SUDOERS.new"
chmod 440 "$SUDOERS.new"
visudo -cf "$SUDOERS.new" >/dev/null || { rm -f "$SUDOERS.new"; fail "The sudoers rule didn't validate."; }
mv "$SUDOERS.new" "$SUDOERS"

echo "Ready. Jobs run as $JOB_USER. Start runners with: node runnerbox.js up --config <this install's config>"
`;
}
