import type { HostInstall } from "../launcher/launcher-config.ts";
import { PRIVATE_RANGES } from "./pf-rules.ts";
import { RUNNER_RELEASE } from "./runner-release.ts";
import { psQuote, windowsPaths } from "./windows-paths.ts";

// IPv6 is blocked whole, as on the other kinds: unique local, link-local, multicast and global.
const IPV6 = ["fc00::/7", "fe80::/10", "ff00::/8", "2000::/3"];

// The script `host render` writes for Windows. Run from an elevated PowerShell by the user who'll
// run `up`, from the folder it was rendered into. It can be run again after a config change or a
// runnerbox update.
export function windowsSetupScript(config: HostInstall) {
  const paths = windowsPaths(config);
  const q = psQuote;

  return `# Sets this PC up to run jobs as a separate user. Generated by runnerbox host render. Review it,
# and run-job.ps1 next to it, then run it from an elevated PowerShell:
#   powershell -ExecutionPolicy Bypass -File .\\setup.ps1
param([string]$Owner = "$env:USERDOMAIN\\$env:USERNAME")
$ErrorActionPreference = 'Stop'
Set-Location -LiteralPath $PSScriptRoot
$jobUser = ${q(config.host.user)}
$dir = ${q(paths.dir)}
$spool = ${q(paths.spool)}
$handoff = ${q(paths.handoff)}
$runTask = ${q(paths.runTask)}
$jobTask = ${q(paths.jobTask)}
$firewallGroup = ${q(paths.firewallGroup)}
$runnerArchive = ${q(paths.runnerArchive)}
$runnerUrl = ${q(RUNNER_RELEASE.win32.url)}
$runnerSha256 = ${q(RUNNER_RELEASE.win32.sha256)}

$identity = [Security.Principal.WindowsIdentity]::GetCurrent()
if (-not ([Security.Principal.WindowsPrincipal]$identity).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
  throw 'Run from an elevated PowerShell.'
}
$ownerSid = (New-Object Security.Principal.NTAccount($Owner)).Translate([Security.Principal.SecurityIdentifier]).Value
foreach ($file in 'run-job.ps1', 'job.ps1') { if (-not (Test-Path -LiteralPath $file)) { throw "$file is missing next to setup.ps1." } }
if (Get-NetFirewallProfile | Where-Object { -not $_.Enabled }) { throw 'Windows Firewall is turned off for a network profile. Turn it on first.' }
if (-not (Test-Path -LiteralPath 'C:\\Program Files\\Git\\bin\\bash.exe')) { throw 'Install Git for Windows first: workflows need its bash.' }

# The account jobs run as: standard, hidden from the sign-in screen, with a password nobody knows.
# The job task stores that password, so each run of this script sets a new one.
$bytes = New-Object byte[] 32
[Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
$plain = [Convert]::ToBase64String($bytes) + 'aA1!'
$password = ConvertTo-SecureString $plain -AsPlainText -Force
$account = Get-LocalUser -Name $jobUser -ErrorAction SilentlyContinue
if ($account) {
  # An account that already exists is only reused if an earlier run of this script made it,
  # because every job wipes it.
  if ($account.Description -ne 'runnerbox jobs') { throw "$jobUser already exists and wasn't created by this script. Pick another name." }
  Set-LocalUser -Name $jobUser -Password $password
} else {
  $account = New-LocalUser -Name $jobUser -Password $password -Description 'runnerbox jobs' -PasswordNeverExpires -UserMayNotChangePassword
  Add-LocalGroupMember -SID 'S-1-5-32-545' -Member $jobUser
}
$jobSid = $account.SID.Value
if ($jobSid -eq $ownerSid) { throw "The job user can't be your own account." }
if (Get-LocalGroupMember -SID 'S-1-5-32-544' | Where-Object { $_.SID.Value -eq $jobSid }) { throw "$jobUser is an administrator. Pick another name." }
$hidden = 'HKLM:\\SOFTWARE\\Microsoft\\Windows NT\\CurrentVersion\\Winlogon\\SpecialAccounts\\UserList'
New-Item -Path $hidden -Force | Out-Null
New-ItemProperty -Path $hidden -Name $jobUser -Value 0 -PropertyType DWord -Force | Out-Null

# Program Files lets everyone read and only administrators write, which suits the scripts. The
# spool is closed to everyone but the owner, and the handoff is the one folder the job user may write.
New-Item -ItemType Directory -Path $dir, $spool, $handoff -Force | Out-Null
foreach ($file in 'run-job.ps1', 'job.ps1') { Copy-Item -LiteralPath $file -Destination $dir -Force }
if (Test-Path -LiteralPath 'job-started.ps1') { Copy-Item -LiteralPath 'job-started.ps1' -Destination $dir -Force }
else { Remove-Item -LiteralPath "$dir\\job-started.ps1" -Force -ErrorAction SilentlyContinue }
icacls $spool /inheritance:r /grant:r '*S-1-5-18:(OI)(CI)F' '*S-1-5-32-544:(OI)(CI)F' "*\${ownerSid}:(OI)(CI)M" | Out-Null
if ($LASTEXITCODE -ne 0) { throw "couldn't set the spool folder's permissions." }
icacls $handoff /inheritance:r /grant:r '*S-1-5-18:(OI)(CI)F' '*S-1-5-32-544:(OI)(CI)F' "*\${jobSid}:(OI)(CI)M" | Out-Null
if ($LASTEXITCODE -ne 0) { throw "couldn't set the handoff folder's permissions." }

if (-not ((Test-Path -LiteralPath $runnerArchive) -and (Get-FileHash -LiteralPath $runnerArchive -Algorithm SHA256).Hash -eq $runnerSha256)) {
  $ProgressPreference = 'SilentlyContinue'
  Invoke-WebRequest -Uri $runnerUrl -OutFile "$runnerArchive.part" -UseBasicParsing
  if ((Get-FileHash -LiteralPath "$runnerArchive.part" -Algorithm SHA256).Hash -ne $runnerSha256) { throw "The runner download doesn't match its checksum." }
  Move-Item -LiteralPath "$runnerArchive.part" -Destination $runnerArchive -Force
}

# Windows Firewall can match the account a connection belongs to. It doesn't filter loopback.
Get-NetFirewallRule -Group $firewallGroup -ErrorAction SilentlyContinue | Remove-NetFirewallRule
New-NetFirewallRule -DisplayName "runnerbox ${config.name}: no private networks for $jobUser" -Group $firewallGroup -Direction Outbound -Action Block \`
  -LocalUser "D:(A;;CC;;;$jobSid)" -RemoteAddress ${[...PRIVATE_RANGES, ...IPV6].map(q).join(", ")} | Out-Null

# Laptops would otherwise refuse to start a job on battery, or stop one when unplugged.
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Hours 12)
$powershell = "$env:SystemRoot\\System32\\WindowsPowerShell\\v1.0\\powershell.exe"
$run = New-ScheduledTaskAction -Execute $powershell -Argument "-NoProfile -NonInteractive -ExecutionPolicy Bypass -File \`"$dir\\run-job.ps1\`""
Register-ScheduledTask -TaskName $runTask -Action $run -Settings $settings -User 'SYSTEM' -RunLevel Highest -Force | Out-Null
$job = New-ScheduledTaskAction -Execute $powershell -Argument "-NoProfile -NonInteractive -ExecutionPolicy Bypass -File \`"$dir\\job.ps1\`""
Register-ScheduledTask -TaskName $jobTask -Action $job -Settings $settings -User $jobUser -Password $plain -Force | Out-Null

# The owner may start that one task from an ordinary, unelevated session, and nothing else.
$service = New-Object -ComObject Schedule.Service
$service.Connect()
$task = $service.GetFolder('\\').GetTask($runTask)
$task.SetSecurityDescriptor($task.GetSecurityDescriptor(4) + "(A;;GRGX;;;$ownerSid)", 0)

Write-Output "Ready. Jobs run as $jobUser. Start runners with: node runnerbox.js up --config <this install's config>"
`;
}
