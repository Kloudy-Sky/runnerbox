import type { HostRunnerType } from "../launcher/launcher-config.ts";

// The script the runner runs before a job's first step. It fails every job whose workflow isn't on
// the kind's list, so a pull request or another workflow can't run on this machine by naming its
// label. The job can't change it: root owns the file, and the runner reads the workflow ref from
// GitHub before any of the job's code runs. The config only allows pattern characters that are
// safe unquoted, and `*` has to stay unquoted to match.
export function jobStartedHook(allowedWorkflows: NonNullable<HostRunnerType["allowedWorkflows"]>) {
  return `#!/bin/bash
# Generated by \`runnerbox host render\`.
set -euo pipefail
case "\${GITHUB_WORKFLOW_REF:-}" in
  ${allowedWorkflows.join("|")}) exit 0 ;;
esac
echo "::error::This runner doesn't accept jobs from \${GITHUB_WORKFLOW_REF:-an unknown workflow}."
exit 1
`;
}
